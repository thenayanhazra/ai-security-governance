def governance_json(controls_data: dict, refs: dict, kris_data: dict, threats_data: dict) -> str:
    payload = {
        "schema_version": SCHEMA_VERSION,
        "source": "https://github.com/thenayanhazra/ai-security-governance",
        "frameworks": refs["frameworks"],
        "tiers": {str(k): v for k, v in TIERS.items()},
        "impacts": IMPACTS,
        "approval_matrix": APPROVAL_MATRIX,
        "domains": controls_data["domains"],
        "controls": [
            {
                **c,
                "domain": controls_data["domains"][c["id"].split("-")[0]],
                "applies_from": applies_from(c),
            }
            for c in controls_data["controls"]
        ],
        "kris": kris_data["kris"],
        "components": threats_data["components"],
        "threats": threats_data["threats"],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def oscal_catalog_json(controls_data: dict, refs: dict) -> str:
    groups = []
    for code, name in controls_data["domains"].items():
        group_controls = []
        for c in (c for c in controls_data["controls"] if c["id"].startswith(code + "-")):
            props = [
                {"name": "min-tier", "value": str(c["min_tier"])},
                {"name": "applies-from", "value": applies_from(c)},
            ]
            if c.get("or_impact"):
                props.append({"name": "or-impact", "value": c["or_impact"]})
            for key, _ in COLUMNS:
                for val in c.get(key, []):
                    props.append({"name": key.replace("_", "-"), "value": val})
            for tool in c.get("tooling", []):
                props.append({"name": "open-source-tooling", "value": tool})
            group_controls.append(
                {
                    "id": c["id"].lower(),
                    "title": c["title"],
                    "props": props,
                    "parts": [
                        {"id": f"{c['id'].lower()}_stmt", "name": "statement", "prose": c["requirement"].strip()},
                        {"id": f"{c['id'].lower()}_evid", "name": "assessment-objective", "prose": c["evidence"]},
                    ],
                }
            )
        groups.append({"id": code.lower(), "title": name, "controls": group_controls})

    catalog = {
        "catalog": {
            "uuid": str(uuid.uuid5(OSCAL_NAMESPACE, f"ai-security-governance-catalog-{SCHEMA_VERSION}")),
            "metadata": {
                "title": "AI Security Governance Control Catalogue",
                "version": SCHEMA_VERSION,
                "oscal-version": "1.1.2",
                "remarks": "Generated from data/controls.yaml and data/references.yaml.",
                "props": [
                    {"name": f"framework-{k.replace('_', '-')}", "value": fw["version"]}
                    for k, fw in refs["frameworks"].items()
                ],
            },
            "groups": groups,
        }
    }
    return json.dumps(catalog, indent=2, ensure_ascii=False) + "\n"


