"""Generate the control catalogue and crosswalk from data/controls.yaml.

    python tools/build.py           # write generated files
    python tools/build.py --check   # fail if generated files are out of date
"""

from __future__ import annotations

import csv
import io
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
GENERATED_NOTE = "<!-- Generated by tools/build.py from data/controls.yaml. Do not edit by hand. -->\n\n"
TIERS = {0: "0 Assist", 1: "1 Retrieve", 2: "2 Act with approval", 3: "3 Act autonomously"}
COLUMNS = [
    ("nist_ai_rmf", "NIST AI RMF"),
    ("iso_42001", "ISO/IEC 42001"),
    ("eu_ai_act", "EU AI Act"),
    ("owasp_llm", "OWASP LLM 2026"),
    ("owasp_asi", "OWASP Agentic 2026"),
    ("mitre_atlas", "MITRE ATLAS"),
]
TOOL_LINKS = {
    "AI-Threat-Modelling-Engine": "https://github.com/thenayanhazra/AI-Threat-Modelling-Engine",
    "MCP-Adversarial-Harness": "https://github.com/thenayanhazra/MCP-Adversarial-Harness",
    "Skill-Agent-File-Linter": "https://github.com/thenayanhazra/Skill-Agent-File-Linter",
    "LLM-Prompt-Injection-Fuzzer": "https://github.com/thenayanhazra/LLM-Prompt-Injection-Fuzzer",
}
TOOL_NAMES = {
    "AI-Threat-Modelling-Engine": "AI Threat Modelling Engine",
    "MCP-Adversarial-Harness": "MCP Adversarial Harness",
    "Skill-Agent-File-Linter": "agentlint",
    "LLM-Prompt-Injection-Fuzzer": "LLM Prompt Injection Fuzzer",
}


def load() -> tuple[dict, dict]:
    data = yaml.safe_load((ROOT / "data/controls.yaml").read_text())
    refs = yaml.safe_load((ROOT / "data/references.yaml").read_text())
    return data, refs


def fmt(values: list[str]) -> str:
    return ", ".join(values) if values else "—"


def catalogue(data: dict, refs: dict) -> str:
    out = [GENERATED_NOTE, "# Control catalogue\n\n"]
    out.append(
        f"{len(data['controls'])} controls in {len(data['domains'])} domains. Each control states what must be true, "
        "the evidence an assessor would ask for, the lowest autonomy tier it applies to, and where it maps "
        "in the major frameworks. Tiers are defined in the "
        "[risk framework](ai-agent-risk-framework.md#autonomy-tiers).\n\n"
    )
    out.append("| Domain | Controls |\n|---|---|\n")
    for code, name in data["domains"].items():
        ids = [c["id"] for c in data["controls"] if c["id"].startswith(code + "-")]
        links = ", ".join(f"[{i}](#{i.lower()})" for i in ids)
        out.append(f"| {name} | {links} |\n")
    out.append("\n")
    for code, name in data["domains"].items():
        out.append(f"## {name}\n\n")
        for c in (c for c in data["controls"] if c["id"].startswith(code + "-")):
            out.append(f"### {c['id']}\n\n**{c['title']}**\n\n")
            out.append(f"{c['requirement'].strip()}\n\n")
            out.append(f"- **Applies from:** tier {TIERS[c['min_tier']]}\n")
            out.append(f"- **Evidence:** {c['evidence']}\n")
            for key, label in COLUMNS:
                vals = c.get(key, [])
                if vals:
                    if key in ("owasp_llm", "owasp_asi"):
                        vals = [f"{v} {refs[key][v]}" for v in vals]
                    out.append(f"- **{label}:** {', '.join(vals)}\n")
            if c.get("tooling"):
                tools = ", ".join(f"[{TOOL_NAMES[t]}]({TOOL_LINKS[t]})" for t in c["tooling"])
                out.append(f"- **Open-source tooling:** {tools}\n")
            out.append("\n")
    return "".join(out)


def crosswalk_csv(data: dict) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["id", "title", "min_tier"] + [label for _, label in COLUMNS])
    for c in data["controls"]:
        w.writerow([c["id"], c["title"], c["min_tier"]] + ["; ".join(c.get(k, [])) for k, _ in COLUMNS])
    return buf.getvalue()


def crosswalk_md(data: dict, refs: dict) -> str:
    out = [GENERATED_NOTE, "# Crosswalk\n\n"]
    out.append(
        "Two views of the same mappings. The first lists each control against every framework. "
        "The second starts from each framework entry and shows which controls address it, so gaps are visible. "
        "Machine-readable version: [crosswalk.csv](crosswalk.csv).\n\n"
    )
    out.append("Framework versions:\n\n")
    for key, _ in COLUMNS:
        fw = refs["frameworks"][key]
        out.append(f"- **{fw['name']}:** {fw['version']}\n")
    out.append("\n## By control\n\n")
    out.append("| Control | " + " | ".join(label for _, label in COLUMNS) + " |\n")
    out.append("|---" * (len(COLUMNS) + 1) + "|\n")
    for c in data["controls"]:
        link = f"[{c['id']}](../framework/control-catalogue.md#{c['id'].lower()})"
        out.append(f"| {link} {c['title']} | " + " | ".join(fmt(c.get(k, [])) for k, _ in COLUMNS) + " |\n")

    out.append("\n## By framework entry\n\n")
    for key, label in [("owasp_asi", "OWASP Top 10 for Agentic Applications 2026"),
                       ("owasp_llm", "OWASP Top 10 for LLM Applications 2026"),
                       ("eu_ai_act", "EU AI Act"),
                       ("iso_42001", "ISO/IEC 42001 Annex A"),
                       ("nist_ai_rmf", "NIST AI RMF")]:
        out.append(f"### {label}\n\n| Entry | Controls |\n|---|---|\n")
        for entry, desc in refs[key].items():
            ids = [c["id"] for c in data["controls"] if entry in c.get(key, [])]
            cell = ", ".join(f"[{i}](../framework/control-catalogue.md#{i.lower()})" for i in ids) if ids else "*Not mapped*"
            out.append(f"| {entry} {desc} | {cell} |\n")
        out.append("\n")
    return "".join(out)


def outputs() -> dict[Path, str]:
    data, refs = load()
    return {
        ROOT / "framework/control-catalogue.md": catalogue(data, refs),
        ROOT / "crosswalk/crosswalk.csv": crosswalk_csv(data),
        ROOT / "crosswalk/crosswalk.md": crosswalk_md(data, refs),
    }


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date (run python tools/build.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
