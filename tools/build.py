def outputs(root: Path = ROOT) -> dict[Path, str]:
    controls, refs, kris, threats = load(root)
    gov_json = governance_json(controls, refs, kris, threats)
    return {
        root / "framework/control-catalogue.md": catalogue(controls, refs),
        root / "crosswalk/crosswalk.csv": crosswalk_csv(controls),
        root / "crosswalk/crosswalk.md": crosswalk_md(controls, refs),
        root / "board/kri-library.md": kri_library_md(kris),
        root / "threat-models/agentic-ai-reference-threat-model.md": threat_model_md(threats),
        root / "dist/governance.json": gov_json,
        root / "dist/oscal-catalog.json": oscal_catalog_json(controls, refs),
        root / "docs/control-selector.html": control_selector_html(gov_json),
    }


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    check = "--check" in args
    stale = []
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date (run python tools/build.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
