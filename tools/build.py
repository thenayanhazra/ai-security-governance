def load(root: Path = ROOT) -> tuple[dict, dict, dict, dict]:
    controls = yaml.safe_load((root / "data/controls.yaml").read_text(encoding="utf-8"))
    refs = yaml.safe_load((root / "data/references.yaml").read_text(encoding="utf-8"))
    kris = yaml.safe_load((root / "data/kris.yaml").read_text(encoding="utf-8"))
    threats = yaml.safe_load((root / "data/threats.yaml").read_text(encoding="utf-8"))
    return controls, refs, kris, threats


def fmt(values: list[str]) -> str:
    return ", ".join(values) if values else "—"


def applies_from(control: dict) -> str:
    text = f"tier {TIERS[control['min_tier']]}"
    impact = control.get("or_impact")
    if impact:
        if impact == "severe":
            text += ", or Severe impact"
        else:
            text += f", or {IMPACTS[impact]} impact and above"
    return text


def catalogue(data: dict, refs: dict) -> str:
    out = [GENERATED_NOTE, "# Control catalogue\n\n"]
    out.append(
        f"{len(data['controls'])} controls in {len(data['domains'])} domains. Each control states what must be true, "
        "the evidence an assessor would ask for, the autonomy tier and impact rating that trigger it, and where it maps "
        "in the major frameworks. Tiers and impact ratings are defined in the "
        "[risk framework](ai-agent-risk-framework.md#autonomy-tiers).\n\n"
    )
    out.append("| Domain | Controls |\n|---|---|\n")
    for code, name in data["domains"].items():
        ids = [c["id"] for c in data["controls"] if c["id"].startswith(code + "-")]
        links = ", ".join(f"[{i}](#{i.lower()})" for i in ids)
        out.append(f"| {name} | {links} |\n")
    out.append("\n")
    for code, name in data["domains"].items():
        out.append(f"## {name}\n\n")
        for c in (c for c in data["controls"] if c["id"].startswith(code + "-")):
            out.append(f"### {c['id']}\n\n**{c['title']}**\n\n")
            out.append(f"{c['requirement'].strip()}\n\n")
            out.append(f"- **Applies from:** {applies_from(c)}\n")
            out.append(f"- **Evidence:** {c['evidence']}\n")
            for key, label in COLUMNS:
                vals = c.get(key, [])
                if vals:
                    if key in ("owasp_llm", "owasp_asi", "mitre_atlas"):
                        vals = [f"{v} {refs[key][v]}" for v in vals]
                    out.append(f"- **{label}:** {', '.join(vals)}\n")
            if c.get("tooling"):
                tools = ", ".join(f"[{TOOL_NAMES[t]}]({TOOL_LINKS[t]})" for t in c["tooling"])
                out.append(f"- **Open-source tooling:** {tools}\n")
            out.append("\n")
    return "".join(out)


def crosswalk_csv(data: dict) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["id", "title", "min_tier", "or_impact"] + [label for _, label in COLUMNS])
    for c in data["controls"]:
        w.writerow(
            [c["id"], c["title"], c["min_tier"], c.get("or_impact", "")]
            + ["; ".join(c.get(k, [])) for k, _ in COLUMNS]
        )
    return buf.getvalue()


def crosswalk_md(data: dict, refs: dict) -> str:
    out = [GENERATED_NOTE, "# Crosswalk\n\n"]
    out.append(
        "Two views of the same mappings. The first lists each control against every framework. "
        "The second starts from each framework entry and shows which controls address it, so gaps are visible. "
        "Machine-readable version: [crosswalk.csv](crosswalk.csv).\n\n"
    )
    out.append("Framework versions:\n\n")
    for key, _ in COLUMNS:
        fw = refs["frameworks"][key]
        out.append(f"- **{fw['name']}:** {fw['version']}\n")
    out.append("\n## By control\n\n")
    out.append("| Control | " + " | ".join(label for _, label in COLUMNS) + " |\n")
    out.append("|---" * (len(COLUMNS) + 1) + "|\n")
    for c in data["controls"]:
        link = f"[{c['id']}](../framework/control-catalogue.md#{c['id'].lower()})"
        out.append(f"| {link} {c['title']} | " + " | ".join(fmt(c.get(k, [])) for k, _ in COLUMNS) + " |\n")

    out.append("\n## By framework entry\n\n")
    reverse_views = [
        ("owasp_asi", "OWASP Top 10 for Agentic Applications 2026"),
        ("owasp_llm", "OWASP Top 10 for LLM Applications 2026"),
        ("mitre_atlas", "MITRE ATLAS (agentic and LLM techniques in scope)"),
        ("eu_ai_act", "EU AI Act"),
        ("iso_42001", "ISO/IEC 42001 Annex A"),
        ("nist_ai_rmf", "NIST AI RMF"),
    ]
    for key, label in reverse_views:
        entries = refs[key]
        mapped = sum(1 for entry in entries if any(entry in c.get(key, []) for c in data["controls"]))
        out.append(f"### {label}\n\n{mapped} of {len(entries)} entries mapped.\n\n| Entry | Controls |\n|---|---|\n")
        for entry, desc in entries.items():
            ids = [c["id"] for c in data["controls"] if entry in c.get(key, [])]
            cell = ", ".join(f"[{i}](../framework/control-catalogue.md#{i.lower()})" for i in ids) if ids else "*Not mapped*"
            out.append(f"| {entry} {desc} | {cell} |\n")
        out.append("\n")
    return "".join(out)


def kri_library_md(kris_data: dict) -> str:
    kris = kris_data["kris"]
    out = [GENERATED_NOTE, "# Key risk indicators for AI and agents\n\n"]
    out.append(
        f"{len(kris)} indicators that show whether the [risk framework](../framework/ai-agent-risk-framework.md) "
        "is working. Each one is measurable from systems most organisations already run, and each links to the controls it tests.\n\n"
        "The thresholds are starting points. Calibrate them to the organisation's risk appetite, its size and how many agents "
        "it runs, then hold them steady so trends mean something.\n\n"
    )
    out.append("| ID | Indicator | How it is measured | Green | Amber | Red | Controls |\n")
    out.append("|---|---|---|---|---|---|---|\n")
    for k in kris:
        ctrl_links = ", ".join(f"[{cid}](../framework/control-catalogue.md#{cid.lower()})" for cid in k["controls"])
        out.append(
            f"| {k['id']} | {k['name']} | {k['measure']} | {k['green']} | {k['amber']} | {k['red']} | {ctrl_links} |\n"
        )
    notes = [k for k in kris if k.get("note")]
    if notes:
        out.append("\n## Notes on the harder ones\n\n")
        for k in notes:
            short = k["name"].lower()
            out.append(f"**{k['id']}, {short}.** {k['note'].strip()}\n\n")
    return "".join(out)


